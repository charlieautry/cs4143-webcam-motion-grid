static const char* TEXT_VERT_SRC = R"(
#version 330 core
layout(location = 0) in vec2 aPos;
layout(location = 1) in vec2 aTexCoord;
uniform mat4 projection;
out vec2 TexCoord;
void main() {
    TexCoord = aTexCoord;
    gl_Position = projection * vec4(aPos, 0.0, 1.0);
}
)";

static const char* TEXT_FRAG_SRC = R"(
#version 330 core
in vec2 TexCoord;
uniform sampler2D fontTex;
uniform vec3 textColor;
out vec4 FragColor;
void main() {
    float a = texture(fontTex, TexCoord).r;
    if (a < 0.5) discard;
    FragColor = vec4(textColor, a);
}
)";

void TextRenderer::createFontTexture() {
    // build a 128x96 texture atlas 16 chars wide x 6 rows each char 8x8
    // covers ascii 32-126 95 chars total
    const int ATLAS_W = 128; // 16 * 8
    const int ATLAS_H = 48; // 6 * 8
    std::vector<unsigned char> atlas(ATLAS_W * ATLAS_H, 0);

    for (int ci = 0; ci < 95; ++ci) {
        int col = ci % 16;
        int row = ci / 16;
        for (int y = 0; y < 8; ++y) {
            unsigned char bits = FONT_8X8[ci][y];
            for (int x = 0; x < 8; ++x) {
                if (bits & (0x80 >> x)) {
                    int px = col * 8 + x;
                    int py = row * 8 + y;
                    atlas[py * ATLAS_W + px] = 255;
                }
            }
        }
    }

    glGenTextures(1, &fontTexture_);
    glBindTexture(GL_TEXTURE_2D, fontTexture_);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, ATLAS_W, ATLAS_H, 0,
                 GL_RED, GL_UNSIGNED_BYTE, atlas.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
}

static GLuint compileShader(GLenum type, const char* src) {
    GLuint s = glCreateShader(type);
    glShaderSource(s, 1, &src, nullptr);
    glCompileShader(s);
    return s;
}

void TextRenderer::createShader() {
    GLuint vs = compileShader(GL_VERTEX_SHADER, TEXT_VERT_SRC);
    GLuint fs = compileShader(GL_FRAGMENT_SHADER, TEXT_FRAG_SRC);
    shaderProgram_ = glCreateProgram();
    glAttachShader(shaderProgram_, vs);
    glAttachShader(shaderProgram_, fs);
    glLinkProgram(shaderProgram_);
    glDeleteShader(vs);
    glDeleteShader(fs);
}

void TextRenderer::init() {
    createFontTexture();
    createShader();

    glGenVertexArrays(1, &vao_);
    glGenBuffers(1, &vbo_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    // reserve space for up to 256 chars 6 verts each
    glBufferData(GL_ARRAY_BUFFER, 256 * 6 * 4 * sizeof(float), nullptr, GL_DYNAMIC_DRAW);
    // position
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
    // texcoord
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
    glBindVertexArray(0);
}

void TextRenderer::renderText(const std::string& text, float x, float y,
                               float scale, int screenWidth, int screenHeight) {
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDisable(GL_DEPTH_TEST);

    glUseProgram(shaderProgram_);

    // orthographic projection screen space
    float proj[16] = {0};
    proj[0]  =  2.0f / screenWidth;
    proj[5]  = -2.0f / screenHeight; // flip y so origin sits top left
    proj[10] = -1.0f;
    proj[12] = -1.0f;
    proj[13] =  1.0f;
    proj[15] =  1.0f;
    glUniformMatrix4fv(glGetUniformLocation(shaderProgram_, "projection"), 1, GL_FALSE, proj);
    glUniform3f(glGetUniformLocation(shaderProgram_, "textColor"), 1.0f, 1.0f, 1.0f);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, fontTexture_);
    glUniform1i(glGetUniformLocation(shaderProgram_, "fontTex"), 0);

    const float charW = 8.0f * scale;
    const float charH = 8.0f * scale;
    const float atlasW = 128.0f;
    const float atlasH = 48.0f;

    std::vector<float> verts;
    verts.reserve(text.size() * 6 * 4);

    float curX = x;
    for (char c : text) {
        if (c < 32 || c > 126) c = '?';
        int ci = c - 32;
        int col = ci % 16;
        int row = ci / 16;

        float u0 = (col * 8.0f) / atlasW;
        float v0 = (row * 8.0f) / atlasH;
        float u1 = ((col + 1) * 8.0f) / atlasW;
        float v1 = ((row + 1) * 8.0f) / atlasH;

        float x0 = curX, y0 = y;
        float x1 = curX + charW, y1 = y + charH;

        // two triangles per char swap u0/u1 to fix the horizontal mirror
        float quad[] = {
            x0,y0, u1,v0,  x1,y0, u0,v0,  x1,y1, u0,v1,
            x0,y0, u1,v0,  x1,y1, u0,v1,  x0,y1, u1,v1,
        };
        verts.insert(verts.end(), quad, quad + 24);
        curX += charW;
    }

    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferSubData(GL_ARRAY_BUFFER, 0, verts.size() * sizeof(float), verts.data());
    glDrawArrays(GL_TRIANGLES, 0, (GLsizei)(text.size() * 6));
    glBindVertexArray(0);

    glEnable(GL_DEPTH_TEST);
    glDisable(GL_BLEND);
}

void TextRenderer::cleanup() {
    glDeleteVertexArrays(1, &vao_);
    glDeleteBuffers(1, &vbo_);
    glDeleteProgram(shaderProgram_);
    glDeleteTextures(1, &fontTexture_);
}
